#!/usr/bin/env bash
# Writes LOGINS.local.md: every test account with its role, what to test with it, and the
# passwords from .env.dev. The file is git-ignored; it is for manual testing on this laptop only.
set -euo pipefail
HIKMAH_ENV=dev
. "$(dirname "${BASH_SOURCE[0]}")/../lib.sh"

BASE="$(env_value MOODLE_WWWROOT)"
ADMIN="$(env_value HIKMAH_ADMIN_USER)"
ADMINPASS="$(env_value HIKMAH_ADMIN_PASSWORD)"
DEMO="$(env_value HIKMAH_DEMO_PASSWORD)"
OUT="$ROOT_DIR/LOGINS.local.md"

if [ -z "$DEMO" ]; then
    echo "No demo accounts yet. Run scripts/dev/seed.sh first." >&2
    exit 1
fi

cat > "$OUT" <<EOF
# Hikmah Online — test logins (this laptop only)

Generated by \`scripts/dev/logins.sh\` from \`.env.dev\`. Git-ignored: do not share or commit.
All \`demo.*\` people are fictional. Sign in at $BASE/login/index.php

## Passwords

| Who | Password |
| --- | --- |
| Administrator (\`$ADMIN\`) | \`$ADMINPASS\` |
| Every \`demo.*\` account | \`$DEMO\` |

## Accounts by role

| Role | Username | Use it to test |
| --- | --- | --- |
| Super administrator | \`$ADMIN\` | Site administration, plugin settings, payment accounts, certificate templates. First login asks for gender, date of birth and phone once. |
| Administrator / course manager | \`demo.manager\` | Create and edit courses, enrol users, payment review queue, attendance report and CSV export. |
| Finance reviewer | \`demo.finance\` | Payment review queue: open a receipt, approve, reject, ask to resubmit. Has no access to coursework. |
| Support | \`demo.support\` | Look up users and participants, enter courses, enrol or unenrol manually. |
| Instructor (editing teacher) | \`demo.teacher\` | Teaches Tajweed, Seerah, Fiqh, Tafsir. Course content, grading, attendance reconciliation (course menu > Attendance reconciliation). |
| Instructor (editing teacher) | \`demo.teacher2\` | Teaches Arabic, Fiqh, Hadith. Second instructor on Fiqh (multiple instructors). |
| Instructor (non-editing teacher) | \`demo.assistant\` | Tajweed only: grade and review attendance, cannot edit content. |
| Student, enrolled | \`demo.student1\` | Dashboard with courses, course pages, grades, a verifiable certificate. |
| Student, payment approved or pending | \`demo.student2\` | Paid for Tajweed by bank transfer (pending until a reviewer approves it). |
| Student, asked to resubmit | \`demo.student3\` | Open Tajweed's course page > Resubmit receipt. |
| Student, enrolled | \`demo.student4\` | Tajweed learner; start a new payment on a paid course such as Fiqh of Worship. |
| Student, enrolled | \`demo.student5\` | Tajweed and Hadith learner. |
| Student, payment pending | \`demo.student6\` | Enrolled in Tajweed; has a pending Easypaisa payment for Fiqh of Worship. |
| Visitor (no login) | — | Home, catalog, course pages, FAQ, certificate verification. |

## Useful places

- Home: $BASE/?redirect=0
- Catalog: $BASE/theme/hikmah/catalog.php
- Verify a certificate: $BASE/theme/hikmah/verify.php
- My payments (student): $BASE/payment/gateway/hikmahtransfer/status.php
- Payment review queue (finance, manager): $BASE/payment/gateway/hikmahtransfer/review.php
- Mail inbox for the dev site: http://localhost:$(env_value MAILPIT_PORT)

To test sign-up as a brand-new learner, use "Create account" on the site; the confirmation email
arrives in the mail inbox above.
EOF

echo "Wrote LOGINS.local.md"
